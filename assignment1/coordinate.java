import java.util.Scanner;




public class Coordinate{
	private int x; 
	private int y;

	Coordinate(int x,  int y){
		this.x = x;
		this.y = y;
	}

	public int getX(){
		return this.x;
	}
	public int getY(){
		return this.y;
	}
	public void setX(int setX){
		this.x = setX;
	}
	public void setY(int setY){
		this.y = setY;
	}

	
}
